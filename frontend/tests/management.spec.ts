async function balances(page: Page) {
  const response = await page.request.get("/api/v1/wallets?includeArchived=true"); expect(response.ok()).toBe(true);
  return Object.fromEntries((await response.json()).map((wallet: { name: string; balance: string }) => [wallet.name, wallet.balance]));
}
async function mutation(page: Page, path: string, body: unknown, key?: string) {
  const csrf = await (await page.request.get("/api/v1/auth/csrf")).json();
  const response = await page.request.post(`/api/v1${path}`, { data: body, headers: { [csrf.headerName]: csrf.token, ...(key ? { "Idempotency-Key": key } : {}) } });
  expect(response.ok()).toBe(true); return response.json();
}
